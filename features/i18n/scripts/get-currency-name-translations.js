const fs = require('node:fs/promises')
const path = require('node:path')

const TRANSLATE_API_HOST = 'https://api-free.deepl.com'
const TRANSLATE_API_VERSION = 'v2'
const OUTPUT_DIR = path.resolve(__dirname, '..')

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

function getArgs() {
  const args = process.argv
  const userArgs = args.slice(2)
  let apiVersion = '1'
  let apiHost = 'https://api.freecurrencyapi.com'
  if (userArgs.length > 0) {
    userArgs.forEach((arg) => {
      if (arg.startsWith('host=')) {
        apiHost = arg.split('=')[1]
      }
      if (arg.startsWith('v=')) {
        apiVersion = arg.split('=')[1]
      }
    })
  }

  return {
    apiVersion,
    apiHost,
  }
}

function checkForCurrencyApiKey() {
  if (!process.env.EXPO_PUBLIC_CURRENCY_API_KEY) {
    console.error(
      '[error] 🚫 Can`t find EXPO_PUBLIC_CURRENCY_API_KEY env variable'
    )
    process.exit(1)
  }
}

function checkForTranslationApiKey() {
  if (!process.env.TRANSLATION_API_KEY) {
    console.error('[error] 🚫 Can`t find TRANSLATION_API_KEY env variable')
    process.exit(1)
  }
}

async function getCurrencyData(apiUrl) {
  const req = await fetch(apiUrl, {
    headers: {
      apikey: process.env.EXPO_PUBLIC_CURRENCY_API_KEY,
    },
  })

  if (!req.ok) {
    console.error(
      `[error] 🚫 Request failed. Status code: ${req.status}.${req.message ? ' Message: ' + req.message : ''}`
    )
    process.exit(1)
  }
  const res = await req.json()
  return res.data
}

async function translate(text, targetLang, sourceLang = 'EN') {
  const url = `${TRANSLATE_API_HOST}/${TRANSLATE_API_VERSION}/translate`

  try {
    const payload = {
      target_lang: targetLang,
      source_lang: sourceLang,
      text: [text],
    }

    const req = await fetch(url, {
      method: 'POST',
      headers: {
        Authorization: `DeepL-Auth-Key ${process.env.TRANSLATION_API_KEY}`,
        Accept: 'application/json',
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(payload),
    })

    if (!req.ok) {
      throw new Error(`HTTP error: ${req.status} ${req.statusText}`)
    }

    const resp = await req.json()

    console.log(
      `[info] ✅ translated "${text}" from ${sourceLang} to ${targetLang}`
    )

    return resp.translations[0].text
  } catch (e) {
    console.error(
      `[error] 🚫 ${e instanceof Error ? e.message : 'unknown error ' + String(e)}`
    )
    return text
  }
}

async function main() {
  const { apiVersion, apiHost } = getArgs()
  const apiUrl = `${apiHost}/v${apiVersion}/currencies`

  checkForCurrencyApiKey()
  checkForTranslationApiKey()

  try {
    const currencies = await getCurrencyData(apiUrl)

    const currenciesWithTranslatedNames = {}

    for (const currencyCode of Object.keys(currencies)) {
      const name = currencies[currencyCode].name
      const namePlural = currencies[currencyCode].name_plural
      // we have to add some waiting period between calls
      // or else we'll run into the rate-limit of the API
      const deName = await translate(name, 'DE')
      await sleep(1000)
      const deNamePlural = await translate(namePlural, 'DE')
      await sleep(1000)
      const huName = await translate(name, 'HU')
      await sleep(1000)
      const bgName = await translate(name, 'BG')
      await sleep(1000)
      const bgNamePlural = await translate(namePlural, 'BG')
      currenciesWithTranslatedNames[currencyCode] = {
        name: {
          en: name,
          de: deName,
          hu: huName,
          bg: bgName,
        },
        name_plural: {
          en: namePlural,
          de: deNamePlural,
          // We don't translate currency names' plural from in Hungarian
          // cause we don't use them in that language, so just add the same
          // to keep it consistent
          hu: huName,
          bg: bgNamePlural,
        },
      }
    }

    const translationsFileName = 'currency-name-translations.ts'
    const translationsFileContent = `/* generated by get-currency-name-translations.js */ export const CURRENCY_NAME_TRANSLATIONS = ${JSON.stringify(currenciesWithTranslatedNames)} as const`
    const translationsFilePath = path.join(OUTPUT_DIR, translationsFileName)

    await fs.writeFile(translationsFilePath, translationsFileContent, 'utf-8')

    console.log(
      `[info] Wrote the generated translations to currency-name-translations.ts`
    )
    process.exit(0)
  } catch (e) {
    if (e instanceof Error) {
      console.error(`[error] 🚫 ${e.message}`)
    } else {
      console.error(`[error] 🚫 unknown error: ${String(e)}`)
    }
    process.exit(1)
  }
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
