const fs = require('node:fs/promises')
const path = require('node:path')

const OUTPUT_DIR = path.resolve(__dirname, '..', 'flags')
const LIB_ROOT_DIR = path.resolve(__dirname, '..')

function currencyCodeToCountryCode(currencyCode) {
  const firstTwoLetters = currencyCode[0] + currencyCode[1]
  return firstTwoLetters.toLowerCase()
}

async function fileExists(filePath) {
  try {
    await fs.access(filePath)
    return true
  } catch {
    return false
  }
}

async function downloadFlag(countryCode) {
  const fileName = countryCode + '.png'
  const outputPath = path.join(OUTPUT_DIR, fileName)
  const url = `https://flagcdn.com/w80/${fileName}`

  if (await fileExists(outputPath)) {
    console.log(
      `[info] ⏭️ skipped ${fileName}, path already exists: ${outputPath}`
    )
    return
  }

  try {
    const res = await fetch(url)

    if (!res.ok) {
      console.warn(
        `Warning: ${url} failed with ${res.status} ${res.statusText}`
      )
      return
    }

    const arrayBuffer = await res.arrayBuffer()
    const buffer = Buffer.from(arrayBuffer)

    await fs.writeFile(outputPath, buffer)
    console.log(`[info] ⬇️ downloaded: ${fileName}`)
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    console.warn(`[warning] ⚠️ ${url} failed to download: ${message}`)
  }
}

async function main() {
  const args = process.argv
  const userArgs = args.slice(2)
  let apiVersion = '1'
  let apiHost = 'https://api.freecurrencyapi.com'
  if (userArgs.length > 0) {
    userArgs.forEach((arg) => {
      if (arg.startsWith('host=')) {
        apiHost = arg.split('=')[1]
      }
      if (arg.startsWith('v=')) {
        apiVersion = arg.split('=')[1]
      }
    })
  }
  const apiUrl = `${apiHost}/v${apiVersion}/currencies`

  if (!process.env.EXPO_PUBLIC_CURRENCY_API_KEY) {
    console.error(
      '[error] 🚫 Can`t find EXPO_PUBLIC_CURRENCY_API_KEY env variable'
    )
    process.exit(1)
  }
  try {
    const req = await fetch(apiUrl, {
      headers: {
        apikey: process.env.EXPO_PUBLIC_CURRENCY_API_KEY,
      },
    })
    const res = await req.json()

    if (!req.ok) {
      console.error(
        `[error] 🚫 Request failed. Status code: ${req.status}.${res.message ? ' Message: ' + res.message : ''}`
      )
      process.exit(1)
    }
    const requireListFileName = 'flags.ts'
    const requireListFilePath = path.join(LIB_ROOT_DIR, requireListFileName)

    let flagsContent = `/*generated by get-country-flags.js
                          don't modify by hand!
                        */
                          export const FLAG_IMAGES = {`

    const codes = Object.keys(res.data)

    for (const code of codes) {
      const isoCode = currencyCodeToCountryCode(code)
      flagsContent += `${isoCode}: require('./flags/${isoCode}.png'),`
      await downloadFlag(isoCode)
    }
    flagsContent += '} as const'
    await fs.writeFile(requireListFilePath, flagsContent, 'utf-8')
    console.log(`[info] Downloaded all ${codes.length}`)
    process.exit(0)
  } catch (e) {
    if (e instanceof Error) {
      console.error(`[error] 🚫 ${e.message}`)
    } else {
      console.error(`[error] 🚫 unknown error: ${String(e)}`)
    }
    process.exit(1)
  }
}

main()
